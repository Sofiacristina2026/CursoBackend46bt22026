<?php
declare(strict_types=1);

require_once __DIR__ . '/src/ConexaoBanco.php';

/**
 * Exemplo 3: Paginação segura de catálogo industrial.
 * LIMIT e OFFSET são vinculados explicitamente como inteiros.
 */

try {
    $pdo = ConexaoBanco::obterConexao(
        __DIR__ . '/config/database.ini'
    );
} catch (PDOException $e) {
    die("Erro ao conectar ao banco: " . $e->getMessage());
}

/**
 * Cria a tabela caso ela ainda não exista.
 * Sintaxe compatível com PostgreSQL.
 */
$pdo->exec("
    CREATE TABLE IF NOT EXISTS pecas_industriais (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome VARCHAR(150) NOT NULL
    )
");

/**
 * Insere dados de exemplo somente se a tabela estiver vazia.
 */
$totalExistente = (int) $pdo->query(
    "SELECT COUNT(*) FROM pecas_industriais"
)->fetchColumn();

if ($totalExistente === 0) {
    $stmt = $pdo->prepare(
        "INSERT INTO pecas_industriais (nome) VALUES (:nome)"
    );

    for ($i = 1; $i <= 12; $i++) {
        $stmt->execute([
            ':nome' => "Peça Industrial #$i"
        ]);
    }
}

/**
 * Captura e valida o número da página.
 */
$paginaRecebida = filter_input(INPUT_GET, 'p', FILTER_VALIDATE_INT);
$pagina = ($paginaRecebida !== false
    && $paginaRecebida !== null
    && $paginaRecebida >= 1)
    ? $paginaRecebida
    : 1;

$limitePorPagina = 5;
$offset = ($pagina - 1) * $limitePorPagina;

/**
 * Lista as peças usando paginação segura.
 */
function listarPecasPaginadas(
    PDO $pdo,
    int $limite,
    int $offset
): array {
    $sql = "
        SELECT id, nome
        FROM pecas_industriais
        ORDER BY id
        LIMIT :limite OFFSET :offset
    ";

    $stmt = $pdo->prepare($sql);
    $stmt->bindValue(':limite', $limite, PDO::PARAM_INT);
    $stmt->bindValue(':offset', $offset, PDO::PARAM_INT);
    $stmt->execute();

    return $stmt->fetchAll(PDO::FETCH_ASSOC);
}

$total = (int) $pdo->query(
    "SELECT COUNT(*) FROM pecas_industriais"
)->fetchColumn();

$totalPaginas = max(1, (int) ceil($total / $limitePorPagina));

// Impede solicitar uma página maior que o total disponível.
if ($pagina > $totalPaginas) {
    $pagina = $totalPaginas;
    $offset = ($pagina - 1) * $limitePorPagina;
}

$pecas = listarPecasPaginadas(
    $pdo,
    $limitePorPagina,
    $offset
);

echo "=== CATÁLOGO INDUSTRIAL ===\n";
echo "Página $pagina de $totalPaginas\n\n";

foreach ($pecas as $peca) {
    echo "[ID: {$peca['id']}] {$peca['nome']}\n";
}

echo "\nTotal de peças: $total\n";